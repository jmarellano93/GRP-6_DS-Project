# ------------------------------------------------------------------------------
# [INSERTED] EXPERIMENT: Optimizing K for KNN Imputation (RMSE Method)
# ------------------------------------------------------------------------------
# PURPOSE: To verify if the default K=5 is actually optimal for this dataset.
# METHODOLOGY: 
# 1. Isolate complete cases (rows with no NAs) from the Training set.
# 2. Artificially introduce NAs into a numeric column (e.g., AMT_INCOME_TOTAL_LOG).
# 3. Test different K values (3, 5, 7, etc.) and calculate RMSE against known truths.
# NOTE ON METRIC SELECTION (RMSE):
# We use RMSE (Root Mean Squared Error) to evaluate K. 
# While our final goal is Classification (Accuracy/AUC), optimizing Imputation 
# via RMSE is a standard heuristic. It assumes that minimizing the error in 
# reconstructing the data leads to a dataset that best reflects reality, 
# thereby providing the best signal for the Neural Network.
# ------------------------------------------------------------------------------

cat("\n[Experiment] Determining Optimal K for KNN Imputation...\n")

# 1. Create a testing subset from Train (Complete cases only)
# We need complete cases to have a "ground truth" to compare against.
df_experiment <- df_train[complete.cases(df_train), ]

if(nrow(df_experiment) > 100) { # Only run if we have enough complete data
  
  # --- [FIX ADDED] Handle Zero Variance Columns ---
  # In this subset of complete cases, some columns might be constant (all 0s or all 1s).
  # Scaling requires variance > 0. We drop constant columns for this specific experiment.
  zero_var_cols <- sapply(df_experiment, function(x) length(unique(x)) == 1)
  if(any(zero_var_cols)) {
    # Keep TARGET even if constant (unlikely), but drop others
    cols_to_drop <- names(df_experiment)[zero_var_cols]
    cols_to_drop <- cols_to_drop[cols_to_drop != "TARGET"] # Safety check
    
    if(length(cols_to_drop) > 0){
      cat(paste("   >> Note: Dropping constant columns for experiment:", paste(cols_to_drop, collapse=", "), "\n"))
      df_experiment <- df_experiment[, !names(df_experiment) %in% cols_to_drop]
    }
  }
  # ------------------------------------------------
  
  # 2. Setup K-values to test
  k_candidates <- c(3, 5, 7, 9, 11, 15, 21)
  rmse_results <- data.frame(k = k_candidates, RMSE = NA)
  
  # 3. Target variable for testing (we introduce artificial NAs here)
  # We use 'AMT_INCOME_TOTAL_LOG' as a proxy because it's continuous and correlated with others.
  target_col <- "AMT_INCOME_TOTAL_LOG"
  actuals <- df_experiment[[target_col]]
  
  # Create synthetic NAs (remove 10% of data)
  set.seed(999) # Local seed for this specific experiment
  na_indices <- sample(1:nrow(df_experiment), 0.1 * nrow(df_experiment))
  df_with_holes <- df_experiment
  df_with_holes[[target_col]][na_indices] <- NA
  
  # 4. Loop through K values
  cat("   Testing K values: ")
  for(i in 1:length(k_candidates)) {
    k_val <- k_candidates[i]
    cat(k_val, "... ")
    
    # Train imputer on the dataset with holes
    # Note: method="knnImpute" in caret automatically scales data (center/scale)
    model <- preProcess(df_with_holes, method = c("knnImpute"), k = k_val)
    
    # Predict (Impute)
    imputed_data <- predict(model, df_with_holes)
    
    # Extract imputed values
    imputed_vals <- imputed_data[[target_col]][na_indices]
    
    # IMPORTANT: caret outputs SCALED values. We must compare against SCALED actuals.
    actuals_scaled <- scale(actuals)[na_indices]
    
    # Calculate RMSE (Root Mean Squared Error)
    rmse <- sqrt(mean((imputed_vals - actuals_scaled)^2))
    rmse_results$RMSE[i] <- rmse
  }
  cat("Done.\n")
  
  # 5. Select Best K
  best_k <- rmse_results$k[which.min(rmse_results$RMSE)]
  
  cat("\n   [Results] RMSE per K-value:\n")
  print(rmse_results)
  cat(paste("\n>> OPTIMAL K FOUND:", best_k, "\n"))
  
} else {
  cat(">> WARNING: Not enough complete cases to run K-optimization. Defaulting to K=5.\n")
  best_k <- 5
}

# --- Phase 2. Define Preprocessing Pipeline ---

# ==============================================================================
# IMPUTATION DECISION JUSTIFICATION
# ==============================================================================
# Why we chose KNN over Mean/Median or Bagged Trees:
#
# 1. vs. Mean/Median Imputation:
#    - Mean imputation replaces missing values with the average of that column.
#    - FLAW: It ignores relationships between columns (e.g., Higher Income usually 
#      means Higher Credit). Mean imputation flattens this variance and bias results.
#    - KNN preserves these correlations by looking at "neighbors".
#
# 2. vs. Bagged Trees:
#    - Bagged trees are often the "Gold Standard" for accuracy.
#    - FLAW: They are extremely computationally expensive (slow) on large datasets.
#    - KNN provides a balance: much better accuracy than Mean, but faster than Trees.
# ==============================================================================

# ==============================================================================
# HOW KNN WORKS (Explanation)
# ==============================================================================
# 1. Identification: The algorithm identifies rows that have missing values.
# 2. Distance Calculation: For a row with a missing value (Row A), it scans 
#    the *other* columns (columns that are NOT missing).
# 3. Neighbor Matching: It finds 'k' other rows in the dataset (Rows B, C, D...) 
#    that have very similar values in those *other* columns.
#    (e.g., If Row A has missing Income, but Age=30 and Job=Admin, it looks for 
#     other rows where Age is near 30 and Job is Admin).
# 4. Imputation: It takes the average Income of those neighbors (B, C, D) and 
#    assigns it to Row A.
# ==============================================================================

