save_plots_to_pdf <- function(raw_df, cleaned_df) {
  
  # Close any open devices to prevent errors
  while(!is.null(dev.list())) dev.off()
  
  ts <- format(Sys.time(), "%d.%m.%Y.(%H%M)")
  filename <- paste0("Autogenerated_Plots_", ts, ".pdf")
  full_path <- file.path(plot_dir, filename)
  
  cat("\nStarting PDF Generation to:", full_path, "\n")
  
  pdf(file = full_path, width = 10, height = 7)
  
  # Ensure device closes even if an error occurs
  on.exit(if(dev.cur() > 1) dev.off())
  
  tryCatch({
    # --- RAW DATA SECTION ---
    cat("... Adding Raw Data EDA\n")
    if(exists("perform_initial_eda") && is.function(perform_initial_eda)) {
      perform_initial_eda(raw_df) 
    } else {
      cat("   [NOTE] Function 'perform_initial_eda' not found (Script is linear).\n")
      cat("   Attempting to print saved 'p_anomaly' from Module 2 if available...\n")
      if(exists("p_anomaly")) print(p_anomaly)
    }
    
    # --- CLEANED DATA SECTION ---
    cat("... Adding Cleaned Data EDA\n")
    if(exists("perform_eda") && is.function(perform_eda)) {
      perform_eda(cleaned_df)
    } else {
      cat("   [NOTE] Function 'perform_eda' not found (Script is linear).\n")
      cat("   Attempting to print saved plots from Module 4 if available...\n")
      
      # Attempt to print plots that typically survive the linear script run
      if(exists("p_target")) { plot(p_target + ggtitle("Target Distribution (Recovered)")) }
      if(exists("p_age"))    { plot(p_age) }
      if(exists("p_bivar"))  { plot(p_bivar) }
      if(exists("cor_mat"))  { 
        corrplot::corrplot(cor_mat, method="circle", type="lower", title="Correlation (Recovered)", mar=c(0,0,2,0)) 
      }
    }
    
  }, error = function(e) {
    cat("ERROR during plotting: ", e$message, "\n")
  })
  
  cat("PDF Generation Complete.\n")
  return(full_path)
}

